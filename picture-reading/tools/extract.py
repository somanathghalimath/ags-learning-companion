"""Offline asset builder. Requires Python/Pillow and Poppler's pdftoppm.
Run: python3 picture-reading/tools/extract.py
No extraction dependencies are used by the application.
"""
from pathlib import Path
import csv, hashlib, json, re, subprocess, tempfile
from PIL import Image, ImageDraw, ImageFont
from inventory_source import PAGES
from cleanup import ERASE, KEEP
ROOT = Path(__file__).resolve().parents[1]
def slug(s): return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')
# Previously flagged crops accepted by the user on 2026-10-28.
APPROVED_REVIEW_ITEMS = {7: {'Eagle','Peacock','Owl'}, 8: {'Shark'},
 13: {'Turnip'},21: {'Scissors'},22: {'Vest'},
 25: {'Tea Pot','Cup','Saucer','Knife','Fork'},
 31: {'Sitar'},32: {'Nail','Screw Nail'},
 36: {'India','National Bird'},38: {'Tree','Flowers','Grass','Clouds','Rainbow','Rain'}}
rows=[];categories={}
with tempfile.TemporaryDirectory(prefix='picture-reading-work-') as work:
 tmp='/tmp/picture-reading-rendered'
 Path(tmp).mkdir(exist_ok=True)
 fingerprint=hashlib.sha256((ROOT/'Adobe Scan 23 Sep 2026.pdf').read_bytes()).hexdigest()
 marker=Path(tmp)/'source.sha256'
 if not Path(tmp+'/page-39.png').exists() or not marker.exists() or marker.read_text()!=fingerprint:
  subprocess.run(['pdftoppm','-scale-to','2400','-png',str(ROOT/'Adobe Scan 23 Sep 2026.pdf'),tmp+'/page'],check=True)
  marker.write_text(fingerprint)
 for page,(title,content) in PAGES.items():
  cid=slug(title);cat=categories.setdefault(cid,dict(id=cid,title=title,type='full-page' if content is None else 'image-grid',items=[]))
  im=Image.open(f'{tmp}/page-{page:02}.png').convert('RGB');scale=max(im.height/490,im.width/350)
  entries=[(title,None)] if content is None else [(line.split('|')[0],list(map(int,line.split('|')[1].split()))) for line in content.splitlines()]
  for name,box in entries:
   path=f'assets/{"full-pages" if box is None else cid}/{slug(name)}.webp'
   dest=ROOT/path;dest.parent.mkdir(parents=True,exist_ok=True)
   if box is None:
    asset=im
   else:
    coords=[round(n*scale) for n in box]
    coords=[max(0,min(v,im.width if i%2==0 else im.height)) for i,v in enumerate(coords)]
    asset=im.crop(coords)
    key=(page,name)
    if key in KEEP:
     mask=Image.new('L',asset.size,0)
     ImageDraw.Draw(mask).polygon([(round(x*asset.width/100),round(y*asset.height/100)) for x,y in KEEP[key]],fill=255)
     white=Image.new('RGB',asset.size,'white');white.paste(asset,(0,0),mask);asset=white
    draw=ImageDraw.Draw(asset)
    for rect in ERASE.get(key,[]):
     draw.rectangle([round(v*(asset.width if i%2==0 else asset.height)/100) for i,v in enumerate(rect)],fill='white')
   asset.save(dest,'WEBP',quality=94 if box is None else 90,method=6)
   status='approved' if name in APPROVED_REVIEW_ITEMS.get(page,set()) else 'extracted'
   rows.append(dict(sourcePage=page,textbookPage=1 if page==1 else page-1,category=title,name='' if box is None else name,type=cat['type'],image=path,status=status,notes='Contextual or overlapping artwork; accepted as-is by the user on 2026-10-28.' if status=='approved' else ''))
   if box is None:
    cat.pop('items',None);cat.update(image=path,sourcePage=page)
   else: cat['items'].append(dict(id=slug(name),name=name,image=path,sourcePage=page,reviewStatus=status))
rows.insert(5,dict(sourcePage=2,textbookPage=1,category='Domestic Animals',name='',type='image-grid',image='',status='duplicate-skipped',notes='Same five illustrations as PDF page 1.'))
(ROOT/'data').mkdir(exist_ok=True)
(ROOT/'data/picture-reading.js').write_text('/* Generated by tools/extract.py; source labels are preserved. */\nconst pictureReading = '+json.dumps(list(categories.values()),indent=2)+';\n')
with (ROOT/'review/inventory.csv').open('w') as f:
 writer=csv.DictWriter(f,fieldnames=list(rows[0]));writer.writeheader();writer.writerows(rows)
font=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',16)
for cid,cat in categories.items():
 if cat['type']=='full-page': continue
 items=cat['items']; sheet=Image.new('RGB',(1000,((len(items)+3)//4)*225+40),'#f3f8fc');d=ImageDraw.Draw(sheet);d.text((12,10),cat['title'],font=font,fill='#17324d')
 for i,item in enumerate(items):
  x=i%4*250;y=i//4*225+40;im=Image.open(ROOT/item['image']);im.thumbnail((230,185));sheet.paste(im,(x+(250-im.width)//2,y))
  d.text((x+8,y+190),item['name'],font=font,fill='#17324d')
  if item['reviewStatus']=='needs-review': d.text((x+8,y+208),'REVIEW',font=font,fill='#a63220')
 sheet.save(ROOT/f'review/{cid}.jpg',quality=90)
html='<!doctype html><meta charset="utf-8"><title>Extraction review</title><style>body{font:18px system-ui;margin:24px}img{display:block;max-width:100%;height:auto;margin-bottom:32px}a{display:inline-block;margin:8px}</style><h1>Picture Reading extraction review</h1><p>All 23 previously flagged items were accepted as-is by the user on 2026-10-28. See inventory.csv for approval records.</p>'
for cid,cat in categories.items():
 html+=f'<h2>{cat["title"]}</h2><img loading="lazy" src="'+(f'../{cat["image"]}' if cat['type']=='full-page' else f'{cid}.jpg')+'">'
(ROOT/'review/index.html').write_text(html)
print(f'{len(categories)} categories; {len(rows)-5} object images; four full pages; one duplicate skipped.')
