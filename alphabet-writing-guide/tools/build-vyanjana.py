"""Rebuild reviewed consonant centrelines using only Python's standard library.

Run from any directory. Optional --references GIF_DIRECTORY also extracts the
source final-frame crops (requires Pillow); it never downloads media.
Source paths, movement frame ranges and hashes live in review/vyanjana-construction.json.
"""
from pathlib import Path
import argparse, hashlib, json, re
ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--references', type=Path)
args = parser.parse_args()
construction = json.loads((ROOT/'review/vyanjana-construction.json').read_text())
output = []
for c in construction:
    left, top, right, bottom = c['sourceBounds']
    scale = 280 / max(right-left, bottom-top)
    cx, cy = (left+right)/2, (top+bottom)/2
    strokes = []
    for stroke in c['strokes']:
        # Input is reviewed absolute M/L/C geometry. No font outline traversal.
        assert re.fullmatch(r'[MLC\s\d.\-]+', stroke['d'])
        axis = iter([0, 1] * 1000)
        def transform(match):
            coordinate = (float(match[0]) - (cx, cy)[next(axis)]) * scale + 200
            return f'{coordinate:.2f}'
        path = re.sub(r'-?\d+(?:\.\d+)?', transform, stroke['d'])
        s = {'d': path, 'prompt': stroke['prompt'], 'sourceFrames': stroke['sourceFrames']}
        if 'sourceWidth' in stroke:
            s['strokeWidth'] = round(stroke['sourceWidth'] * scale, 2)
        strokes.append(s)
    output.append({
        'name':c['name'], 'id':c['id'], 'strokes':strokes,
        'source':f"https://commons.wikimedia.org/wiki/File:Kannada-alphabet-{c['file']}.gif",
        'referenceImage':f"vyanjana-references/{c['id']}.png",
        'reconstructionNote':c.get('junctionNote','Smooth monoline reconstruction; see construction notes for simplifications.'),
        'movementNote':'One continuous pen-down movement.' if len(strokes)==1 else 'Lift the pencil only between the numbered strokes.'
    })
    if args.references:
        from PIL import Image
        source = args.references / f"Kannada-alphabet-{c['file']}.gif"
        assert hashlib.sha256(source.read_bytes()).hexdigest() == c['sourceSHA256'], source
        with Image.open(source) as image:
            image.seek(image.n_frames-1)
            directory = ROOT/'review/vyanjana-references'
            directory.mkdir(exist_ok=True)
            image.convert('RGB').crop((max(0,left-8),max(0,top-8),right+9,bottom+9)).save(directory/f"{c['id']}.png", optimize=True)
header = '''"use strict";
/* Hand-reconstructed pencil centrelines adapted from Gopala Krishna A's
 * Kannada handwriting animations, CC BY-SA 4.0. Source movement windows,
 * geometry decisions, checksums and attribution: review/KANNADA-VYANJANA-SOURCES.md.
 * Changes: smooth monoline reconstruction, normalised scale, explicit dot taps,
 * movement prompts and review diagrams. Adapted path contributions: CC BY-SA 4.0.
 * https://creativecommons.org/licenses/by-sa/4.0/
 * Generated by tools/build-vyanjana.py; edit review/vyanjana-construction.json.
 */
window.KANNADA_VYANJANAS = '''
(ROOT/'kannada-vyanjana.js').write_text(header + json.dumps(output,ensure_ascii=False,indent=2) + ';\n')
print(f'Built {len(output)} consonants, {sum(len(c["strokes"]) for c in output)} pen-down movements.')
